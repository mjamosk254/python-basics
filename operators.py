#arithmetic operators-help us do basic math
x=10
y=5
print(x+y)
print(x-y)
print(x*y)
print(x/y)
print(x%y)#modulus or remider
print(x**y)#power

#comparison-lets you compare two value - the answer is always true or false
a=20
b=15
print(a==b)#equal to
print(a!=b)#not equal to
print(a<b)#less than
print(a>b)#greater than
print(a<=b)#less than or equal to
print(a>=b)#greater than or equal to